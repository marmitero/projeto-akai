"""Freeze the approved 150..190 ASPD curve as integer intervals, independent of FPS."""
from decimal import Decimal,localcontext,ROUND_CEILING
from pathlib import Path
with localcontext() as c:
 c.prec=60
 values=[int(max(Decimal(200),1000-800*(Decimal(i)/1000)**Decimal('1.25')).to_integral_value(rounding=ROUND_CEILING)) for i in range(1001)]
p=Path(__file__).resolve().parents[2]/'packages/shared/src/combat-speed-v3.ts'
p.write_text('// Generated by scripts/economy-v2/generate-aspd.py\nexport const ATTACK_INTERVAL_V3 = [\n'+''.join('  '+','.join(map(str,values[i:i+20]))+',\n' for i in range(0,len(values),20))+'] as const;\n')
