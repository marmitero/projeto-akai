"""Frozen material curve, Decimal 60 digits; no fractional powers in runtime."""
from decimal import Decimal,localcontext,ROUND_FLOOR
from pathlib import Path
with localcontext() as c:
 c.prec=60
 lines=['// Generated by scripts/economy-v2/generate-hunts.py; units per victory.','export const HUNT_MATERIAL_V4={']
 for kind,base in [('coal',4),('iron',8),('gold',2)]:
  values=[int((Decimal(base)*((Decimal(1)+Decimal(f-1)/5)**Decimal('.65'))).to_integral_value(rounding=ROUND_FLOOR)) for f in range(1,1001)]
  lines.append(kind+':['+','.join(map(str,values))+'],')
 lines.append('} as const;')
 Path('packages/shared/src/hunt-material-v4.ts').write_text('\n'.join(lines)+'\n')
