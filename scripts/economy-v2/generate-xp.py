"""Freeze R1.1 weights into integer milliseconds; runtime never evaluates powers."""
from decimal import Decimal, localcontext, ROUND_FLOOR
from pathlib import Path
with localcontext() as ctx:
    ctx.prec = 70
    weights = [Decimal('.05') + 2*(Decimal(n)/999)**Decimal('1.7') for n in range(1,1000)]
    total = sum(weights)
    thresholds, cumulative = [0], Decimal(0)
    for weight in weights:
        cumulative += weight
        thresholds.append(int((cumulative/total*8294400000).to_integral_value(rounding=ROUND_FLOOR)))
    thresholds[-1] = 8294400000
path=Path(__file__).resolve().parents[2]/'packages/shared/src/economy-xp-v2.ts'
path.write_text('// Generated by scripts/economy-v2/generate-xp.py; XP units are integer milliseconds.\nexport const ECONOMY_XP_V2 = [\n'+''.join('  '+','.join(map(str,thresholds[i:i+10]))+',\n' for i in range(0,1000,10))+'] as const;\n')
